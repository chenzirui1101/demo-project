class Command(BaseCommand):
    help = '导入兴宁市旅游景点种子数据（20+景点）'

    def handle(self, *args, **options):
        Banner.objects.all().delete()
        Attraction.objects.all().delete()
        Category.objects.all().delete()

        cat_map = {}
        for idx, c in enumerate(CATEGORIES):
            cat = Category.objects.create(name=c["name"], icon=c["icon"], sort=idx)
            cat_map[c["name"]] = cat
        self.stdout.write(self.style.SUCCESS(f'创建 {len(cat_map)} 个分类'))

        created = []
        for idx, item in enumerate(ATTRACTIONS):
            (name, cat_name, cover_prompt, brief, desc, loc,
             price, open_time, rating, lng, lat, hot, rec) = item
            ids = PICSUM_IDS.get(name, [1018, 1043, 1050])
            cover = img(ids[0], 800, 500)
            images = json.dumps([
                img(ids[0], 800, 600),
                img(ids[1 % len(ids)], 800, 500),
                img(ids[2 % len(ids)], 800, 450),
            ], ensure_ascii=False)
            attraction = Attraction.objects.create(
                name=name, category=cat_map[cat_name], cover=cover, images=images,
                description=brief + "\n\n" + desc, location=loc, longitude=lng, latitude=lat,
                ticket_price=price, open_time=open_time, rating=rating,
                view_count=(hot * 500 + 200), is_hot=hot, is_recommended=rec,
            )
            created.append(attraction)
        self.stdout.write(self.style.SUCCESS(f'创建 {len(created)} 个景点'))

        banners = [a for a in created if a.is_recommended][:5]
        for idx, a in enumerate(banners):
            Banner.objects.create(
                title=a.name, image=a.cover, link_type='attraction',
                attraction=a, sort=idx, is_active=True,
            )
        self.stdout.write(self.style.SUCCESS(f'创建 {len(banners)} 个轮播图'))

        if not User.objects.filter(username='admin').exists():
            user = User.objects.create_user(username='admin', password='admin123')
            UserProfile.objects.create(user=user, nickname='兴宁游客', phone='13800138000')
            self.stdout.write(self.style.SUCCESS('创建测试用户 admin/admin123'))

        self.stdout.write(self.style.SUCCESS('种子数据导入完成!'))
